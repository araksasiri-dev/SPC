import re

def verify_username(username):
    # ด่าน 1: เช็กห้ามมีช่องว่าง (Space) เด็ดขาด
    if ' ' in username:
        return False, "Username ห้ามมีช่องว่างเด็ดขาด"
        
    # ด่าน 2: เช็กประเภทอักษร (ย้ายขึ้นมาด่านแรก และเพิ่ม _ เข้าไปในกฎอนุญาต)
    # [a-zA-Z0-9_] หมายถึง ยอมรับภาษาอังกฤษ ตัวเลข และเครื่องหมายขีดล่างเท่านั้น
    if not re.match(r"^[a-zA-Z0-9_]+$", username):
        return False, "Username ห้ามมีภาษาไทย หรืออักขระพิเศษเด็ดขาด"

    # ด่าน 3: เช็กตัวแรกสุด ต้องเริ่มด้วยตัวอักษรภาษาอังกฤษเท่านั้น
    if not re.match(r"^[a-zA-Z]", username):
        return False, "Username ต้องขึ้นต้นด้วยตัวอักษรภาษาอังกฤษ (A-Z, a-z) เท่านั้น"
        
    # ด่าน 4: เช็กความยาวต้องอยู่ระหว่าง 6 ถึง 15 ตัวอักษร
    if not (6 <= len(username) <= 15):
        return False, f"Username ต้องยาวระหว่าง 6-15 ตัวอักษร (ปัจจุบัน {len(username)} ตัว)"
    
    # ถ้าหลุดรอดมาได้ทั้งหมด แปลว่าปลอดภัย
    return True, "Username ถูกต้องตามกฎความปลอดภัย"